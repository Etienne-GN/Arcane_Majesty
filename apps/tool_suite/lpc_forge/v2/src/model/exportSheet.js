/**
 * Export model (pure): the Universal LPC sheet layout, the files a character
 * really draws (as the game resolves them — fallbacks and borrowed sources are
 * what ends up on screen, so they are what must be credited), and the credits text.
 */
import { MOTION_FRAMES, libPath } from '../../../../../amo/src/systems/lpcLayout.js';
import { resolveAnim } from '../../../../../amo/src/systems/animResolve.js';
import { resolveMotion } from '../../../../../amo/src/systems/motionRules.js';
import { layerKeyOf } from './composition.js';

// The Universal LPC generator's sheet (lpc_universal/sources/state/constants.ts):
// first row of each motion, in 64 px cells; walk keeps its standing column.
const ORDER = [
    ['spellcast', 0], ['thrust', 4], ['walk', 8], ['slash', 12], ['shoot', 16], ['hurt', 20], ['climb', 21],
    ['idle', 22], ['jump', 26], ['sit', 30], ['emote', 34], ['run', 38], ['combat_idle', 42],
    ['backslash', 46], ['halfslash', 50],
];
export const UNIVERSAL_ROWS = ORDER.map(([motion, row]) => ({
    motion, row,
    rows: motion === 'hurt' || motion === 'climb' ? 1 : 4,
    cols: MOTION_FRAMES[motion] + (motion === 'walk' ? 1 : 0),
}));

export function universalSize() {
    const last = UNIVERSAL_ROWS.reduce((a, r) => Math.max(a, r.row + r.rows), 0);
    return { w: Math.max(...UNIVERSAL_ROWS.map(r => r.cols)) * 64, h: last * 64 };
}

/**
 * Every file the character draws in `motions`: [{ path, layerKey, motions }],
 * library-relative paths. `hasFile(layer, concrete)` (optional) reports what
 * exists; like the game, a missing file falls back to walk, and a layer with
 * neither is reported { path: null, missing: true }.
 */
export function filesUsed(layers, motions, rules = {}, overrides, hasFile) {
    const out = new Map();
    const add = (k, base, m) => {
        const e = out.get(k) ?? { ...base, motions: [] };
        if (!e.motions.includes(m)) e.motions.push(m);
        out.set(k, e);
    };
    for (const layer of layers) {
        const layerKey = layerKeyOf(layer);
        for (const m of motions) {
            const res = resolveMotion(layer, m, rules, overrides);
            if (res.mode === 'hide') continue;
            let concrete = res.concrete;
            if (hasFile && !hasFile(layer, concrete)) {
                const walk = resolveAnim(layer, 'walk') ?? 'walk';
                concrete = hasFile(layer, walk) ? walk : null;
            }
            if (!concrete) { add(`missing:${layerKey}`, { path: null, layerKey }, m); continue; }
            const path = libPath(layer, concrete);
            add(path, { path, layerKey }, m);
        }
    }
    return [...out.values()].map(e => (e.path === null ? { ...e, missing: true } : e));
}

const isProblem = r => r.path === null || r.error || !r.licenses?.length || r.licenses.includes('unknown');
const problemName = r => (r.path === null ? `${r.layerKey} (no file)` : r.path);

/** Paths whose provenance must be checked before shipping (no credit, unknown licence, no file). */
export function licenceProblems(rows) {
    return rows.filter(isProblem).map(problemName);
}

/** CREDITS.md: identical attributions grouped, files listed under each; problems first. */
export function creditsMarkdown(name, rows) {
    const lines = [`# Credits — ${name}`, '',
        'Generated by LPC Forge from the sprite sheets this character uses (including',
        "sheets a layer falls back to or borrows). Art from the Liberated Pixel Cup",
        'community; keep these notices with the images (CC-BY-SA / OGA-BY / GPL require attribution).', ''];
    const problems = rows.filter(isProblem);
    if (problems.length) {
        lines.push('## Check these', '', 'No credit or an unknown licence was found for:', '');
        for (const r of problems) lines.push(`- ${problemName(r)}${r.error ? ` — ${r.error}` : ''}`);
        lines.push('');
    }
    const groups = new Map();
    for (const r of rows) {
        if (r.path === null || r.error) continue;
        const key = JSON.stringify([r.authors ?? [], r.licenses ?? [], r.urls ?? []]);
        (groups.get(key) ?? groups.set(key, []).get(key)).push(r);
    }
    lines.push('## Attribution', '');
    for (const [key, files] of groups) {
        const [authors, licenses, urls] = JSON.parse(key);
        lines.push(`- Authors: ${authors.join(', ') || '—'}`, `  Licences: ${licenses.join(', ') || '—'}`);
        if (urls.length) lines.push(`  Links: ${urls.join(' ')}`);
        lines.push('  Files:');
        for (const f of files) lines.push(`  - ${f.path}${f.custom ? ' (drawn in LPC Forge; derived from the files credited here)' : ''}`);
        lines.push('');
    }
    return lines.join('\n');
}
